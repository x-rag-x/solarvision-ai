"""
SolarVision AI — Model 3: Sandia Solar Electrical Performance Prediction
Orchestration Service, Status Monitoring, and Inference Coordination
"""

from __future__ import annotations

import logging
import time
from typing import Any, Dict, List, Optional

from .model_loader import SandiaModelLoader
from .schemas import (
    MAX_BATCH_SIZE,
    SANDIA_CONTRACT_VERSION,
    SandiaBatchPredictionInput,
    SandiaBatchPredictionResponse,
    SandiaModelStatus,
    SandiaModelStatusResponse,
    SandiaPredictionInput,
    SandiaPredictionItem,
    SandiaPredictionResponse,
)

logger = logging.getLogger("solarvision.sandia_performance.service")


class SandiaPerformanceService:
    """Coordinates Sandia electrical performance model loading, feature validation, and inference."""

    def __init__(self, loader: Optional[SandiaModelLoader] = None) -> None:
        self.loader = loader or SandiaModelLoader()

    def get_status(self) -> SandiaModelStatusResponse:
        """Returns readiness, schema discovery status, and artifact provenance without leaking filesystem paths."""
        is_ready = self.loader.is_ready
        status = SandiaModelStatus.READY if is_ready else SandiaModelStatus.NOT_TRAINED
        trainer_pending = not (self.loader.is_ready and not self.loader.is_mock)

        return SandiaModelStatusResponse(
            model_name="SolarVision-Sandia-Performance-Model3",
            model_version=self.loader.model_version,
            contract_version=SANDIA_CONTRACT_VERSION,
            is_ready=is_ready,
            status=status,
            artifact_name=self.loader.artifact_name,
            unavailability_reason=self.loader.unavailability_reason if not is_ready else None,
            feature_schema_loaded=self.loader.feature_schema is not None,
            feature_schema=self.loader.feature_schema.model_dump() if self.loader.feature_schema else None,
            sample_input_loaded=self.loader.sample_input is not None,
            sample_input=self.loader.sample_input,
            target_definition_loaded=self.loader.target_definition is not None,
            target_definition=self.loader.target_definition.model_dump() if self.loader.target_definition else None,
            is_mock=self.loader.is_mock,
            trainer_handoff_pending=trainer_pending,
            expected_dim=self.loader.expected_dim,
        )

    def predict(self, input_data: SandiaPredictionInput) -> SandiaPredictionResponse:
        """Executes single prediction with timing and error isolation."""
        start_time = time.perf_counter()

        if not self.loader.is_ready:
            elapsed = round((time.perf_counter() - start_time) * 1000, 2)
            return SandiaPredictionResponse(
                contract_version=SANDIA_CONTRACT_VERSION,
                status=SandiaModelStatus.NOT_TRAINED,
                model_name="SolarVision-Sandia-Performance-Model3",
                model_version=self.loader.model_version,
                is_mock=False,
                prediction=None,
                limitations=[
                    self.loader.unavailability_reason,
                    "Zero synthetic predictions or fabricated performance metrics are returned.",
                ],
                processing_time_ms=elapsed,
            )

        try:
            prediction_item: SandiaPredictionItem = self.loader.predict(input_data)
            elapsed = round((time.perf_counter() - start_time) * 1000, 2)

            limitations: List[str] = []
            if prediction_item.is_mock:
                limitations.append(
                    "ISOLATED TEST MOCK: This prediction was generated by an automated test mock fixture, "
                    "not a trained production pipeline."
                )

            return SandiaPredictionResponse(
                contract_version=SANDIA_CONTRACT_VERSION,
                status=SandiaModelStatus.READY,
                model_name="SolarVision-Sandia-Performance-Model3",
                model_version=self.loader.model_version,
                is_mock=prediction_item.is_mock,
                prediction=prediction_item,
                limitations=limitations,
                processing_time_ms=elapsed,
            )

        except ValueError as val_err:
            elapsed = round((time.perf_counter() - start_time) * 1000, 2)
            logger.warning("Feature validation error in Sandia prediction: %s", val_err)
            return SandiaPredictionResponse(
                contract_version=SANDIA_CONTRACT_VERSION,
                status=SandiaModelStatus.VALIDATION_ERROR,
                model_name="SolarVision-Sandia-Performance-Model3",
                model_version=self.loader.model_version,
                is_mock=self.loader.is_mock,
                prediction=None,
                limitations=[f"Validation error: {val_err}"],
                processing_time_ms=elapsed,
            )

        except Exception as exc:
            elapsed = round((time.perf_counter() - start_time) * 1000, 2)
            logger.error("Inference execution failure in Sandia service: %s", exc, exc_info=True)
            return SandiaPredictionResponse(
                contract_version=SANDIA_CONTRACT_VERSION,
                status=SandiaModelStatus.ERROR,
                model_name="SolarVision-Sandia-Performance-Model3",
                model_version=self.loader.model_version,
                is_mock=self.loader.is_mock,
                prediction=None,
                limitations=["An internal error occurred during inference execution."],
                processing_time_ms=elapsed,
            )

    def predict_batch(self, batch_input: SandiaBatchPredictionInput) -> SandiaBatchPredictionResponse:
        """Executes batch inference across multiple inputs with batch size safety limits."""
        start_time = time.perf_counter()

        if len(batch_input.items) > MAX_BATCH_SIZE:
            elapsed = round((time.perf_counter() - start_time) * 1000, 2)
            return SandiaBatchPredictionResponse(
                contract_version=SANDIA_CONTRACT_VERSION,
                status=SandiaModelStatus.VALIDATION_ERROR,
                model_name="SolarVision-Sandia-Performance-Model3",
                model_version=self.loader.model_version,
                is_mock=False,
                predictions=[],
                total_items=0,
                limitations=[f"Batch size {len(batch_input.items)} exceeds maximum limit of {MAX_BATCH_SIZE} items."],
                processing_time_ms=elapsed,
            )

        if not self.loader.is_ready:
            elapsed = round((time.perf_counter() - start_time) * 1000, 2)
            return SandiaBatchPredictionResponse(
                contract_version=SANDIA_CONTRACT_VERSION,
                status=SandiaModelStatus.NOT_TRAINED,
                model_name="SolarVision-Sandia-Performance-Model3",
                model_version=self.loader.model_version,
                is_mock=False,
                predictions=[],
                total_items=0,
                limitations=[self.loader.unavailability_reason],
                processing_time_ms=elapsed,
            )

        predictions: List[SandiaPredictionItem] = []
        is_mock = False

        for item in batch_input.items:
            pred_item = self.loader.predict(item)
            if pred_item.is_mock:
                is_mock = True
            predictions.append(pred_item)

        elapsed = round((time.perf_counter() - start_time) * 1000, 2)

        limitations: List[str] = []
        if is_mock:
            limitations.append("Contains mock predictions from automated test mock fixture.")

        return SandiaBatchPredictionResponse(
            contract_version=SANDIA_CONTRACT_VERSION,
            status=SandiaModelStatus.READY,
            model_name="SolarVision-Sandia-Performance-Model3",
            model_version=self.loader.model_version,
            is_mock=is_mock,
            predictions=predictions,
            total_items=len(predictions),
            limitations=limitations,
            processing_time_ms=elapsed,
        )

    def get_schema(self) -> Dict[str, Any]:
        """Returns the loaded feature schema or pending status."""
        if self.loader.feature_schema:
            return {
                "status": "loaded",
                "schemaVersion": self.loader.feature_schema.schema_version,
                "datasetName": self.loader.feature_schema.dataset_name,
                "expectedFeatureCount": len(self.loader.feature_schema.features),
                "features": [f.model_dump() for f in self.loader.feature_schema.features],
                "metadata": self.loader.feature_schema.metadata,
            }
        return {
            "status": "pending_trainer",
            "schemaVersion": SANDIA_CONTRACT_VERSION,
            "message": "Feature schema (feature_schema.json) has not yet been delivered by model trainer.",
        }

    def get_sample_input(self) -> Dict[str, Any]:
        """Returns sample input matching trainer schema or pending status."""
        if self.loader.sample_input:
            return {
                "status": "loaded",
                "sampleInput": self.loader.sample_input,
            }
        return {
            "status": "pending_trainer",
            "message": "Sample input (sample_input.json) has not yet been provided by model trainer.",
        }

    def get_target_definition(self) -> Dict[str, Any]:
        """Returns target definition read dynamically from target_definition.json or pending status."""
        if self.loader.target_definition:
            return {
                "status": "loaded",
                "targetDefinition": self.loader.target_definition.model_dump(),
            }
        return {
            "status": "pending_trainer",
            "message": "Target definition (target_definition.json) has not yet been delivered by model trainer.",
        }

    def get_metadata(self) -> Dict[str, Any]:
        """Returns complete Model 3 Sandia provenance and architecture metadata without exposing internal paths."""
        return {
            "modelId": "sandia-electrical-performance-v1",
            "modelName": "SolarVision PV Electrical Performance Forecaster (Sandia)",
            "framework": "scikit-learn (.joblib pipeline)",
            "contractVersion": SANDIA_CONTRACT_VERSION,
            "domain": "solar_photovoltaic_performance",
            "sourceDataset": "Sandia National Laboratories PV Performance Modeling Telemetry",
            "attribution": "Sandia National Laboratories Photovoltaic Systems Evaluation Laboratory (PSEL)",
            "isReady": self.loader.is_ready,
            "isMock": self.loader.is_mock,
            "artifactName": self.loader.artifact_name,
            "limitations": [
                "Requires calibrated sensor telemetry defined by trainer feature_schema.json.",
                "Inference requires trained scikit-learn .joblib pipeline.",
                "Zero fabrication guarantee: when model artifacts are absent, HTTP 503 is returned rather than fabricated numbers.",
            ],
        }


sandia_performance_service = SandiaPerformanceService()
