/**
 * SolarVision AI — Model 3: Sandia Solar Electrical Performance Prediction
 * Persistence Repository, Multi-Tenant Authorization, and Database Adapter
 */

import { randomUUID } from "node:crypto";
import type { DatabaseSync } from "node:sqlite";
import { getSqliteDb } from "../../sqlite";
import { ensureSandiaPerformanceSchema, SANDIA_TABLE_NAME } from "./schema";
import type {
  InsertSandiaPredictionRecord,
  PaginatedSandiaResult,
  RequesterContext,
  SandiaHistoryQueryOptions,
  SandiaPredictionRecord,
  SandiaReadinessSummary,
} from "../types";

export class SandiaPersistenceRepository {
  private dbInstance: DatabaseSync | null = null;

  constructor(customDb?: DatabaseSync) {
    if (customDb) {
      this.dbInstance = customDb;
      ensureSandiaPerformanceSchema(this.dbInstance);
    }
  }

  private getDb(): DatabaseSync {
    if (this.dbInstance) {
      return this.dbInstance;
    }
    const db = getSqliteDb();
    ensureSandiaPerformanceSchema(db);
    return db;
  }

  /**
   * Maps a raw SQLite row into a strongly typed SandiaPredictionRecord.
   */
  private mapRowToRecord(row: any): SandiaPredictionRecord {
    let inputFeatures: Record<string, any> = {};
    if (row.inputFeatures) {
      try {
        inputFeatures =
          typeof row.inputFeatures === "string"
            ? JSON.parse(row.inputFeatures)
            : row.inputFeatures;
      } catch {
        inputFeatures = {};
      }
    }

    let featuresUsed: string[] | null = null;
    if (row.featuresUsed) {
      try {
        featuresUsed =
          typeof row.featuresUsed === "string"
            ? JSON.parse(row.featuresUsed)
            : row.featuresUsed;
      } catch {
        featuresUsed = null;
      }
    }

    let warnings: string[] | null = null;
    if (row.warnings) {
      try {
        warnings =
          typeof row.warnings === "string"
            ? JSON.parse(row.warnings)
            : row.warnings;
      } catch {
        warnings = null;
      }
    }

    let metadata: Record<string, any> | null = null;
    if (row.metadata) {
      try {
        metadata =
          typeof row.metadata === "string"
            ? JSON.parse(row.metadata)
            : row.metadata;
      } catch {
        metadata = null;
      }
    }

    return {
      id: String(row.id),
      userId: row.userId ?? null,
      moduleId: row.moduleId ?? null,
      inputFeatures,
      predictedValue: Number(row.predictedValue),
      predictionLabel: row.predictionLabel ?? null,
      targetName: String(row.targetName),
      targetUnit: row.targetUnit ?? null,
      confidence: row.confidence != null ? Number(row.confidence) : null,
      uncertainty: row.uncertainty != null ? Number(row.uncertainty) : null,
      featuresUsed,
      modelVersion: String(row.modelVersion || "1.0.0"),
      datasetProvenance: String(
        row.datasetProvenance ||
          "Sandia National Laboratories PV Performance Modeling Telemetry"
      ),
      isMock: Boolean(row.isMock),
      warnings,
      metadata,
      createdAt: String(row.createdAt),
    };
  }

  /**
   * Persists a successful real prediction record.
   * Strictly enforces Task 8: Mock predictions cannot be saved to the database.
   */
  public savePrediction(
    input: InsertSandiaPredictionRecord
  ): SandiaPredictionRecord {
    if (input.isMock) {
      throw new Error(
        "Zero-Fabrication Violation: Mock predictions generated by test fixtures cannot be saved to the production database."
      );
    }

    if (!input.inputFeatures || Object.keys(input.inputFeatures).length === 0) {
      throw new Error(
        "Validation Error: Cannot persist prediction with empty input features."
      );
    }

    if (
      input.predictedValue === undefined ||
      input.predictedValue === null ||
      Number.isNaN(Number(input.predictedValue))
    ) {
      throw new Error(
        "Validation Error: Cannot persist prediction without a valid numeric predicted value."
      );
    }

    if (!input.targetName || typeof input.targetName !== "string") {
      throw new Error(
        "Validation Error: Target variable name must be supplied dynamically from model target definition."
      );
    }

    const db = this.getDb();
    const id = input.id || randomUUID();
    const createdAt = input.createdAt || new Date().toISOString();
    const modelVersion = input.modelVersion || "1.0.0";
    const datasetProvenance =
      input.datasetProvenance ||
      "Sandia National Laboratories PV Performance Modeling Telemetry";

    const stmt = db.prepare(`
      INSERT INTO ${SANDIA_TABLE_NAME} (
        id, userId, moduleId, inputFeatures, predictedValue, predictionLabel,
        targetName, targetUnit, confidence, uncertainty, featuresUsed,
        modelVersion, datasetProvenance, isMock, warnings, metadata, createdAt
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);

    stmt.run(
      id,
      input.userId ?? null,
      input.moduleId ?? null,
      JSON.stringify(input.inputFeatures),
      Number(input.predictedValue),
      input.predictionLabel ?? null,
      input.targetName,
      input.targetUnit ?? null,
      input.confidence != null ? Number(input.confidence) : null,
      input.uncertainty != null ? Number(input.uncertainty) : null,
      input.featuresUsed ? JSON.stringify(input.featuresUsed) : null,
      modelVersion,
      datasetProvenance,
      0, // isMock is strictly 0
      input.warnings ? JSON.stringify(input.warnings) : null,
      input.metadata ? JSON.stringify(input.metadata) : null,
      createdAt
    );

    return {
      id,
      userId: input.userId ?? null,
      moduleId: input.moduleId ?? null,
      inputFeatures: input.inputFeatures,
      predictedValue: Number(input.predictedValue),
      predictionLabel: input.predictionLabel ?? null,
      targetName: input.targetName,
      targetUnit: input.targetUnit ?? null,
      confidence: input.confidence != null ? Number(input.confidence) : null,
      uncertainty: input.uncertainty != null ? Number(input.uncertainty) : null,
      featuresUsed: input.featuresUsed ?? null,
      modelVersion,
      datasetProvenance,
      isMock: false,
      warnings: input.warnings ?? null,
      metadata: input.metadata ?? null,
      createdAt,
    };
  }

  /**
   * Retrieves a prediction by ID with multi-tenant access control.
   */
  public getPredictionById(
    id: string,
    requester?: RequesterContext
  ): SandiaPredictionRecord | null {
    const db = this.getDb();
    const stmt = db.prepare(
      `SELECT * FROM ${SANDIA_TABLE_NAME} WHERE id = ? LIMIT 1`
    );
    const row = stmt.get(id) as any;

    if (!row) {
      return null;
    }

    // Role-based multi-tenant authorization
    const isAdmin = requester?.role === "admin";
    if (
      !isAdmin &&
      requester?.userId &&
      row.userId &&
      row.userId !== requester.userId
    ) {
      return null; // Mask foreign record
    }

    return this.mapRowToRecord(row);
  }

  /**
   * Queries paginated prediction history with ownership isolation and optional filters.
   */
  public getPredictionHistory(
    options: SandiaHistoryQueryOptions = {},
    requester?: RequesterContext
  ): PaginatedSandiaResult {
    const db = this.getDb();
    const limit = Math.max(1, Math.min(100, options.limit ?? 25));
    const offset = Math.max(0, options.offset ?? 0);

    const conditions: string[] = [];
    const params: any[] = [];

    const isAdmin = requester?.role === "admin";
    if (!isAdmin && requester?.userId) {
      conditions.push("userId = ?");
      params.push(requester.userId);
    }

    if (options.moduleId) {
      conditions.push("moduleId = ?");
      params.push(options.moduleId);
    }

    if (options.startDate) {
      conditions.push("createdAt >= ?");
      params.push(options.startDate);
    }

    if (options.endDate) {
      conditions.push("createdAt <= ?");
      params.push(options.endDate);
    }

    const whereClause =
      conditions.length > 0 ? `WHERE ${conditions.join(" AND ")}` : "";

    // Total count query
    const countSql = `SELECT COUNT(*) as total FROM ${SANDIA_TABLE_NAME} ${whereClause}`;
    const countRow = db.prepare(countSql).get(...params) as
      | { total: number }
      | undefined;
    const total = countRow ? Number(countRow.total) : 0;

    // Items query
    const itemsSql = `
      SELECT * FROM ${SANDIA_TABLE_NAME}
      ${whereClause}
      ORDER BY createdAt DESC
      LIMIT ? OFFSET ?
    `;
    const rows = db.prepare(itemsSql).all(...params, limit, offset) as any[];
    const items = rows.map(r => this.mapRowToRecord(r));

    return {
      items,
      total,
      limit,
      offset,
      hasMore: offset + items.length < total,
    };
  }

  /**
   * Returns a readiness count summary of persisted predictions.
   */
  public getReadinessSummary(requester?: RequesterContext): {
    totalPredictions: number;
    distinctModules: number;
    latestPrediction: string | null;
  } {
    const db = this.getDb();
    const conditions: string[] = [];
    const params: any[] = [];

    const isAdmin = requester?.role === "admin";
    if (!isAdmin && requester?.userId) {
      conditions.push("userId = ?");
      params.push(requester.userId);
    }

    const whereClause =
      conditions.length > 0 ? `WHERE ${conditions.join(" AND ")}` : "";

    const statSql = `
      SELECT 
        COUNT(*) as total,
        COUNT(DISTINCT moduleId) as distinctModules,
        MAX(createdAt) as latest
      FROM ${SANDIA_TABLE_NAME}
      ${whereClause}
    `;

    const row = db.prepare(statSql).get(...params) as any;
    return {
      totalPredictions: row ? Number(row.total || 0) : 0,
      distinctModules: row ? Number(row.distinctModules || 0) : 0,
      latestPrediction: row?.latest || null,
    };
  }
}

let _defaultRepo: SandiaPersistenceRepository | null = null;

export function getSandiaRepository(
  customDb?: DatabaseSync
): SandiaPersistenceRepository {
  if (customDb) {
    return new SandiaPersistenceRepository(customDb);
  }
  if (!_defaultRepo) {
    _defaultRepo = new SandiaPersistenceRepository();
  }
  return _defaultRepo;
}

export function persistSandiaPrediction(
  record: InsertSandiaPredictionRecord,
  customDb?: DatabaseSync
): SandiaPredictionRecord {
  return getSandiaRepository(customDb).savePrediction(record);
}

export function getSandiaPredictionById(
  id: string,
  requester?: RequesterContext,
  customDb?: DatabaseSync
): SandiaPredictionRecord | null {
  return getSandiaRepository(customDb).getPredictionById(id, requester);
}

export function getSandiaPredictionHistory(
  options: SandiaHistoryQueryOptions = {},
  requester?: RequesterContext,
  customDb?: DatabaseSync
): PaginatedSandiaResult {
  return getSandiaRepository(customDb).getPredictionHistory(options, requester);
}
